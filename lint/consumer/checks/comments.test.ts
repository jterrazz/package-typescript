import { describe, expect, test } from 'vitest';

import { linesOfComments } from './comments.js';

describe('comments', () => {
    test('counts every line a comment covers, a block from its opening to its closing', () => {
        // Given - a line comment, a trailing one, and a three-line block
        const text = [
            '// a line comment',
            'const one = 1; // a trailing one',
            '/**',
            ' * a block',
            ' */',
            'const two = 2;',
        ].join('\n');

        // Then - five lines are comment lines, the bare statement is not
        expect(linesOfComments(text)).toStrictEqual([1, 2, 3, 4, 5]);
    });

    test('reads a slash inside a string or a template as code', () => {
        // Given - comment markers that only a string and a template hold
        const text = ["const url = 'https://example.com';", 'const glob = `/*.ts`;'].join('\n');

        // Then - no line is a comment line
        expect(linesOfComments(text)).toStrictEqual([]);
    });

    test('leaves a directive to the Suppressions pass', () => {
        // Given - a line whose only comment is a directive, and a line with a prose comment
        const text = [
            '// oxlint-disable-next-line eslint/no-console -- the CLI prints',
            'console.log(1);',
            '// @ts-expect-error -- the fixture is wrong on purpose',
            'const wrong: number = "1";',
            '// prose',
        ].join('\n');

        // Then - only the prose line counts
        expect(linesOfComments(text)).toStrictEqual([5]);
    });

    test('leaves an instruction to a formatter, a coverage tool or a bundler uncounted', () => {
        // Given - the instructions a tool reads, and a prose line
        const text = [
            '// oxfmt-ignore',
            'const matrix = [1,0,0,1];',
            '/* v8 ignore next */',
            'if (matrix.length === 0) throw new Error();',
            'await import(/* @vite-ignore */ path);',
            '// the identity matrix',
        ].join('\n');

        // Then - only the prose line counts
        expect(linesOfComments(text)).toStrictEqual([6]);
    });

    test('leaves a test marker to the test conventions', () => {
        // Given - the markers a test carries, and a prose line inside it
        const text = [
            "test('adds', () => {",
            '    // Given - two numbers',
            '    // When - they are added',
            '    // Then - the sum is theirs',
            '    // the sum is commutative',
            '});',
        ].join('\n');

        // Then - only the prose line counts
        expect(linesOfComments(text)).toStrictEqual([5]);
    });

    test('skips a file a tool generated', () => {
        // Given - a file stamped @generated in its head
        const text = ['// @generated by the schema compiler', '// a line', 'export {};'].join('\n');

        // Then - nothing is counted
        expect(linesOfComments(text)).toStrictEqual([]);
    });
});
