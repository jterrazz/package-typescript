import { describe, expect, test } from 'vitest';

import { commentsOfGo, GO_INSTRUCTION } from '../comments.go.js';

const lines = (...text: string[]): string => text.join('\n');

const openingsOf = (text: string): string[] =>
    commentsOfGo(text).map(({ opening }) => opening.trim());

describe('comments.go', () => {
    test('leaves the documentation of the package and of each exported name, and reads the rest', () => {
        // Given - a package comment, the doc of an exported func, a method, a type and a var, then comments above unexported names and a trailing one
        const text = lines(
            '// Package runtimes lays the runtime folders.',
            'package runtimes',
            '',
            '// Install writes the folders.',
            'func Install() {}',
            '',
            '// Name reads the name of a runtime.',
            'func (r Runtime) Name() string { return r.name }',
            '',
            '// Runtime is one of the supported runtimes.',
            'type Runtime struct{}',
            '',
            '// walk descends the tree.',
            'func walk() {}',
            '',
            'var total = 0 // the count so far',
        );

        // Then - the unexported func's comment and the trailing one
        expect(openingsOf(text)).toStrictEqual(['walk descends the tree.', 'the count so far']);
    });

    test('reads a name declared inside a const block as documented, and a blank line between as no documentation', () => {
        // Given - a block whose first name is documented, and a comment separated from its declaration
        const text = lines(
            'const (',
            '\t// Claude is the default runtime.',
            '\tClaude = "claude"',
            '',
            '\t// gone is not exported.',
            '\tgone = "gone"',
            ')',
            '',
            '// Detached stands apart.',
            '',
            'func Detached() {}',
        );

        // Then - the unexported name's comment and the detached one
        expect(openingsOf(text)).toStrictEqual(['gone is not exported.', 'Detached stands apart.']);
    });

    test('reads a run of lines once, and a build constraint as the comment it is for the pass to recognise', () => {
        // Given - a two-line run above an unexported func, a build constraint, a generator line and a block
        const text = lines(
            '//go:build linux',
            '',
            '//go:generate stringer -type=Kind',
            'package kinds',
            '',
            '// first line',
            '// second line',
            'func run() {}',
            '/* a block',
            '   over lines */',
            'func other() {}',
        );

        // Then - each run opens on its first line, the build constraint among them for the pass to recognise, the generator line above the package clause being its documentation
        expect(openingsOf(text)).toStrictEqual([
            'go:build linux',
            'first line',
            'a block\n   over lines */',
        ]);
    });

    test('reads no comment marker inside a string, a raw string or a rune', () => {
        // Given - a url in a string, a raw string over two lines holding `//`, and a rune
        const text = lines(
            'var a = "https://example.com" // trailing',
            'var b = `line // one',
            '/* two */`',
            "var c = '/'",
        );

        // Then - the one trailing comment
        expect(openingsOf(text)).toStrictEqual(['trailing']);
    });

    test('GO_INSTRUCTION — a comment the go tool reads opens with one of its words, whole, from its first character', () => {
        // Given - the nine openings, each with a word it only starts, and each led by a character
        const read = [
            'go:build linux',
            '+build linux',
            'nolint:errcheck',
            'lint:ignore SA1000',
            'export Foo',
            'line 12',
            'golangci-lint:disable',
            'Code generated by stringer. DO NOT EDIT.',
            '#cgo LDFLAGS: -lm',
        ];
        const ignored = [
            'a go:build linux',
            ' +build linux',
            'nolinter',
            'lint',
            'exported Foo',
            'lines of code',
            'golangci-linter',
            'Code generation',
            'cgo',
        ];

        // Then - the first list is read by the tool, the second is prose
        expect([
            read.map((opening) => GO_INSTRUCTION.test(opening)),
            ignored.map((opening) => GO_INSTRUCTION.test(opening)),
        ]).toStrictEqual([read.map(() => true), ignored.map(() => false)]);
    });

    test('a comment is documentation above a package clause, an exported func, method, type, var, const or block name, and above nothing else', () => {
        // Given - a comment above each line godoc reads, and above lines it does not
        const documented = [
            'package kinds',
            'func Run() {}',
            'func (r Runtime) Run() {}',
            'type  Kind struct{}',
            'var  Total = 0',
            'const  Limit = 1',
            '\tLimit = 1',
            '\tLimit,',
            '\tLimit',
            '  Limit int',
        ];
        const undocumented = [
            ' package kinds',
            'func run() {}',
            'xfunc Run() {}',
            'funcRun() {}',
            'typeKind struct{}',
            'var total = 0',
            'varTotal = 0',
            'constLimit = 1',
            '\tlimit = 1',
            '\tLimit(x)',
            'Limit = 1',
            'x type Kind struct{}',
        ];
        const above = (line: string): string[] => openingsOf(lines('// note', line));

        // Then - the first are the comment's own page, the others leave it to the pass
        expect([
            documented.map((line) => above(line)),
            undocumented.map((line) => above(line)),
        ]).toStrictEqual([documented.map(() => []), undocumented.map(() => ['note'])]);
    });

    test('reads a string with an escaped quote whole, a rune of a quote, and counts the lines a raw string and a block cover', () => {
        // Given - an escaped quote before a marker, a rune holding a double quote, a raw string over three lines, then documentation below each
        const text = lines(
            'var a = "say \\" // not a comment"',
            "var b = '\"'",
            'var c = `one',
            'two // still raw',
            'three`',
            '// Total is documented.',
            'var Total = 1',
            '/* Block',
            '   over lines */',
            'var Other = 2',
            '// Last stands below a block.',
            'var Last = 3',
        );

        // Then - nothing is read as a comment: each string ended where it ended, and every line was counted to find its declaration; and the comment of a block above an exported name is documentation
        expect(openingsOf(text)).toStrictEqual([]);
    });

    test('ends a block that is never closed and a line comment that has no newline at the end of the file, and a quote never closed at the end of the text', () => {
        // Given - a block opened and never closed; a file ending in a line comment; a string opened at the very end
        const unclosed = lines('var a = 1', '/* never closed', 'var b = 2');
        const bare = 'var a = 1 // the end';
        const dangling = 'var a = "never closed';

        // Then - the unclosed block runs to the end of the text; the bare comment is the comment; the dangling string holds no comment
        expect([openingsOf(unclosed), openingsOf(bare), openingsOf(dangling)]).toStrictEqual([
            ['never closed\nvar b = 2'],
            ['the end'],
            [],
        ]);
    });

    test('joins the lines of a run only when each own-line comment follows the last, and never a block', () => {
        // Given - two own-line comments on adjoining lines, two apart, then a block and a line comment, each below a plain line
        const text = lines(
            '// one',
            '// two',
            '',
            '// three',
            '',
            '',
            '// four',
            'var a = 1',
            '/* seven */',
            '// eight',
            'var b = 2',
        );

        // Then - one and two are one run, the rest each stand alone, the block apart from the line comment below it
        expect(commentsOfGo(text).map(({ end, start }) => text.slice(start, end))).toStrictEqual([
            '// one\n// two',
            '// three',
            '// four',
            '/* seven */',
            '// eight',
        ]);
    });
});
