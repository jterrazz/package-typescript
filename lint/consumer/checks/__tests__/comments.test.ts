import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, expect, test } from 'vitest';

import { contextOf } from '../../../kit/checker/checker.js';
import { readCommandLine } from '../../../kit/checker/command-line.js';
import { basePresetsOf } from '../../catalogue/preset.js';
import { comments } from '../comments.js';

const LESSON =
    'found: a comment that states no kind · why: the default is no comment — a script, a style sheet or a workflow speaks through its names as code does, and a comment is kept only for what they cannot say: an invariant, a hazard, a constraint from outside the codebase, why a value is this one · fix: delete it, or open it with its kind — `invariant:`, `hazard:`, `outside:`, `value:` · read: docs/reference/lint-presets.md#a-comment-states-its-kind';

const TREE: Readonly<Record<string, string>> = {
    Makefile: '# The build\nbuild:\n\tnpm run build\n',
    'deploy/run.sh':
        '#!/bin/sh\n# shellcheck disable=SC2086\n# hazard: the tag is pushed first\nset -eu\n',
    'generated.yaml': '# @generated by the schema tool\n# a line\n',
    'index.ts': '// not this pass’s\nexport {};\n',
    'protocol.yaml':
        '# Code generated by protoc-gen-go from the schema, with this tool. DO NOT EDIT.\n# a line\n',
    'pnpm-lock.yaml': '# a lockfile line\n',
    'src/theme.css':
        '/*! kept by minifiers */\n/* stylelint-disable */\n/** invariant: one grid */\na {\n    /* the colour */\n    color: red;\n}\n/* see stylelint-disable */\n',
};

function tree(): string {
    const root = mkdtempSync(join(tmpdir(), 'comments-pass-'));
    for (const [path, text] of Object.entries(TREE)) {
        mkdirSync(dirname(join(root, path)), { recursive: true });
        writeFileSync(join(root, path), text);
    }

    return root;
}

describe('comments', () => {
    test('names each comment of a script, a Makefile, a style sheet or a YAML file that states no kind', async () => {
        // Given - a tree holding kinded, kindless, directive and generated comments, a lockfile and code
        const root = tree();

        // When - the pass reads it
        const result = await comments.check(contextOf(readCommandLine([root]), basePresetsOf));
        rmSync(root, { force: true, recursive: true });

        // Then - the kindless comments, a directive's name in prose among them, each at its place, and nothing written
        expect(result).toStrictEqual({
            after: [],
            findings: [
                {
                    column: 1,
                    line: 1,
                    message: LESSON,
                    path: 'Makefile',
                    rule: 'comments/comment-states-its-kind',
                },
                {
                    column: 5,
                    line: 5,
                    message: LESSON,
                    path: 'src/theme.css',
                    rule: 'comments/comment-states-its-kind',
                },
                {
                    column: 1,
                    line: 8,
                    message: LESSON,
                    path: 'src/theme.css',
                    rule: 'comments/comment-states-its-kind',
                },
            ],
            writes: [],
        });
    });

    test('deletes no comment in fix mode, and reports the same findings', async () => {
        // Given - the same tree
        const root = tree();

        // When - the pass runs in fix mode
        const fixed = await comments.check(
            contextOf(readCommandLine([root, '--fix']), basePresetsOf),
        );
        const read = await comments.check(contextOf(readCommandLine([root]), basePresetsOf));
        rmSync(root, { force: true, recursive: true });

        // Then - nothing is written, and an agent still gets each comment's line to keep or delete
        expect([fixed.after, fixed.writes, fixed.findings]).toStrictEqual([[], [], read.findings]);
    });

    test('reads every directive another tool reads as no prose', async () => {
        // Given - each `#` directive in a script, each style directive in a sheet, and one comment of prose in each
        const root = mkdtempSync(join(tmpdir(), 'comments-directives-'));
        const hashes = [
            'shellcheck disable=SC2086',
            'yamllint disable-line',
            'hadolint ignore=DL3008',
            'oxfmt-ignore',
            'prettier-ignore',
            'dprint-ignore',
            'zizmor: ignore[template-injection]',
            'checkov:skip=CKV_DOCKER_2',
            'nosec',
            'noqa',
            'renovate: datasource=npm',
            'gitleaks:allow',
            'trunk-ignore(all)',
            'syntax=docker/dockerfile:1',
            'escape=`',
            'check=error=true',
            'yaml-language-server: $schema=x.json',
            '@schema x.json',
            '$schema: x.json',
            'region setup',
            'endregion',
            'cspell:disable',
            'codespell:ignore',
            'checker-disable-next-line pinned-value-from-the-input -- the stub clock pins it',
            'invariant: a kind',
            'the prose, which names shellcheck mid-text',
        ];
        const styles = [
            '/*! kept */',
            '/* stylelint-disable */',
            '/* stylelint-enable */',
            '/* biome-ignore lint: x */',
            '/* purgecss start ignore */',
            '/* rtl:ignore */',
            '/* autoprefixer: off */',
            '/* webpackIgnore: true */',
            '/* the prose */',
        ];
        writeFileSync(join(root, 'run.sh'), hashes.map((line) => `# ${line}\nrun\n`).join(''));
        writeFileSync(join(root, 'theme.css'), styles.map((line) => `${line}\na {}\n`).join(''));

        // When - the pass reads them
        const result = await comments.check(contextOf(readCommandLine([root]), basePresetsOf));
        rmSync(root, { force: true, recursive: true });

        // Then - the prose alone, once in each file
        expect(result.findings?.map(({ line, path }) => `${path}:${String(line)}`)).toStrictEqual([
            'run.sh:51',
            'theme.css:17',
        ]);
    });
});
